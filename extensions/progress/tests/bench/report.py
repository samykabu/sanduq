"""Generate docs/token-benchmark.md.

Run from the progress-report skill directory:  python -m tests.bench.report [--check]
`--check` exits 1 when the committed file differs from a fresh run.

A repository that vendors this bench sets, relative to the directory holding `tests/`:
PROGRESS_BENCH_CLI (the CLI line the agent types), PROGRESS_BENCH_SKILL (the skill file it loads)
and PROGRESS_BENCH_DOC (where its own report lives).
"""
import os
import sys
from pathlib import Path

from . import approaches, counting, run, traces

DOC = Path(__file__).resolve().parents[2] / os.environ.get("PROGRESS_BENCH_DOC", "docs/token-benchmark.md")
ORDER = ["NEW", "MD-EDIT", "MD-EDIT-LEAN", "LEGACY", "MD-RENDER"]
DESCRIBE = {
    "NEW": "Progress verbs. The agent types only the CLI line for events no producer records; automatic collection emits nothing.",
    "MD-EDIT": "Hand-maintained Markdown report. Each update reads the affected sections (or the whole file if cheaper), then makes one minimal Edit call per changed hunk.",
    "MD-EDIT-LEAN": "Sensitivity variant of MD-EDIT: no re-reads, Edit calls only. A lower bound for hand maintenance.",
    "LEGACY": "The current Workflow `progress.py` protocol from `execution-report.md`, run for real so every output line is the script's own.",
    "MD-RENDER": "Deterministic Markdown export written by hooks. No tokens per update; reading it costs its size.",
}


def _rows(data, encoding):
    present = [a for a in ORDER if a in data["results"]]
    counts = {c: sum(e["kind"] == c for e in data["trace"]) for c in traces.CLASSES}
    sums = {a: run.per_class(data, a, encoding) for a in present}
    lines = ["| Update class | Events | " + " | ".join(present) + " |", "| --- | ---: | " + " | ".join("---:" for _ in present) + " |"]
    for c in traces.CLASSES:
        lines.append("| `%s` | %d | " % (c, counts[c]) + " | ".join(str(sums[a][c]) for a in present) + " |")
    totals = {a: sum(sums[a].values()) for a in present}
    setup = {a: data["results"][a]["setup"][encoding] for a in present}
    lines.append("| **Updates total** | %d | " % len(data["trace"]) + " | ".join("**%d**" % totals[a] for a in present) + " |")
    lines.append("| Setup (once per feature) | | " + " | ".join(str(setup[a]) for a in present) + " |")
    lines.append("| **Total with setup** | | " + " | ".join("**%d**" % (totals[a] + setup[a]) for a in present) + " |")
    return lines, totals, setup


def _break_even(data, encoding, other):
    new = data["results"]["NEW"]
    ref = data["results"][other]
    a, b = new["setup"][encoding], ref["setup"][encoding]
    for i, (n, r) in enumerate(zip(run.prefix_totals(data, "NEW", encoding), run.prefix_totals(data, other, encoding))):
        if a + n <= b + r:
            return i + 1
    return None


def render(data):
    out = ["# Token benchmark", "",
           "Generated by `python -m tests.bench.report` from the `progress-report` skill. Do not edit by hand.", "",
           "## What is measured", "",
           "Model-visible serialized content for one scripted, 624-like feature: %d updates over 24 tasks and 4 lanes." % len(data["trace"]),
           "For each update the benchmark counts the tool-call arguments the agent emits (as JSON) and the text the tool returns.",
           "Fixed tool framing is identical across approaches and is not counted. Setup costs are listed separately.", ""]
    for a in ORDER:
        if a in data["results"]:
            out.append("- **%s**: %s" % (a, DESCRIBE[a]))
    if "LEGACY" not in data["results"]:
        out.append("- LEGACY was not run: the Sanduq Workflow extension is not present in this checkout.")
    out += ["",
            "## Declared metric and its limits", "",
            "- Declared metric: **o200k_base serialized-content tokens**, counted with tiktoken %s. It is exact for that encoding." % data["tiktoken"],
            "  It is the tokenizer family used by recent GPT models, so for those models the figures are token counts of the content. "
            "They do not include the host's own framing or hidden reasoning.",
            "- `cl100k_base` is shown as a second exact count for an older encoding.",
            "- **Claude: UNVERIFIED.** There is no exact local Claude tokenizer. No Claude figure is claimed. "
            "`counting.claude_estimate` can label an ESTIMATED count when `ANTHROPIC_API_KEY` and the `anthropic` SDK are present; it is not part of this table.",
            "- Bytes are a diagnostic, not a cost.",
            "- Measured usage from real runs belongs in `tests/live_ab.py`, which reports the harness's own token usage.", "",
            "## Assumptions that favour neither side", "",
            "- Producers record what they own. Checking a task off in `tasks.md` happens in every approach, so it is not charged to any of them.",
            "  NEW therefore costs nothing for task start, completion and reopening: the report derives them from `tasks.md`.",
            "- The trace is plain Spec Kit. Under Workflow, lanes, retries and decisions come from its ledger and NEW would cost less.",
            "- NEW lines are the real CLI's own output: the benchmark runs `scripts/progress.py` in a sandbox repository.",
            "- Re-orientation (`resume`, `compaction`) reloads the skill for NEW and the protocol page for LEGACY. MD-EDIT re-reads the whole report. "
            "NEW's `status` line is shorter than a full report read, so it tells the agent less.",
            "- MD-RENDER is the real `export --format md` file. MD-EDIT is a hand-maintained report of the same six sections written by the benchmark.",
            "- LEGACY setup counts `execution-report.md` only. The full execute protocol is longer. Since Workflow 1.10.0 that page also carries the reporting-mode pointer, so it is about 440 tokens larger than the 1.9.x page (o200k_base: 3,484 setup, 11,146 updates).", ""]
    for encoding, title in (("o200k_base", "o200k_base (declared)"), ("cl100k_base", "cl100k_base")):
        rows, totals, setup = _rows(data, encoding)
        out += ["## Results: %s" % title, ""] + rows + [""]
        if encoding == counting.DECLARED:
            declared_totals, declared_setup = totals, setup
    out += ["## Break-even including setup", ""]
    for other in ("MD-EDIT", "MD-EDIT-LEAN", "LEGACY"):
        if other in data["results"]:
            n = _break_even(data, counting.DECLARED, other)
            out.append("- NEW with its setup is at or below %s from update %s onward in this trace." % (
                other, n if n is not None else "none (never within this trace)"))
    out += ["", "## Bytes (diagnostic)", "", "| Approach | Updates | Setup |", "| --- | ---: | ---: |"]
    for a in ORDER:
        if a in data["results"]:
            r = data["results"][a]
            out.append("| %s | %d | %d |" % (a, sum(e["bytes"] for e in r["events"]), r["setup"]["bytes"]))
    prefix_tokens = counting.count(counting.load()[counting.DECLARED], approaches.NEW_CLI)
    ratio = declared_totals["MD-EDIT"] / max(declared_totals["NEW"], 1)
    out += ["", "## Reading the result", "",
            "- Updates only, o200k_base: NEW %d, MD-EDIT %d (%.1fx), MD-EDIT-LEAN %d." % (
                declared_totals["NEW"], declared_totals["MD-EDIT"], ratio, declared_totals["MD-EDIT-LEAN"]),
            "- NEW setup is %d tokens (the skill text plus `init`). The skill loads again after a restart or compaction." % declared_setup["NEW"],
            "- `unblock`, `block`, `decision` and note verbs cost tens of tokens because their command line is the whole cost.",
            "- MD-RENDER is the size of the real export, and it is only comparable when it carries the same content. The first v3 export dropped the Tasks checklist, "
            "which cut a re-read from 1349 to 557 tokens (resume). That was information loss, not a saving. The export now lists every task by phase with its workstream and state, "
            "and the MD-RENDER column is reported as measured with that section included.",
            "- The per-verb prefix `python .claude/skills/progress-report/scripts/progress.py` is %d tokens of each NEW line. A shorter entry point would reduce every NEW figure." % prefix_tokens,
            "", "## Reproduce", "",
            "```bash", "python -m pip install tiktoken==0.14.0",
            "cd skills/agent-tools/skills/progress-report", "python -m tests.bench.report", "python -m unittest discover -s tests -q", "```", ""]
    return "\n".join(out)


def main(argv):
    data = run.compute()
    text = render(data)
    if "--check" in argv:
        current = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
        if current != text:
            print("docs/token-benchmark.md is stale; run python -m tests.bench.report")
            return 1
        return 0
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", DOC)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
